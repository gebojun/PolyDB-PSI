"""Batch-render one property-specific reliability map for each major category.

Every panel C is generated by script 15 and uses only the selected property's
cell-level reliability score. The representative-property list is fixed before
rendering so the selection is not based on the resulting score distribution.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd


REPRESENTATIVE_PROPERTIES = [
    {
        "category": "thermal",
        "property": "Tg_K",
        "selection_basis": "key thermal property",
    },
    {
        "category": "electrical",
        "property": "dielectric_constant",
        "selection_basis": "representative dielectric property",
    },
    {
        "category": "mechanical",
        "property": "tensile_break_GPa",
        "selection_basis": "high-coverage mechanical property",
    },
    {
        "category": "optical",
        "property": "refractive_index",
        "selection_basis": "high-coverage optical property",
    },
    {
        "category": "solution",
        "property": "intrinsic_viscosity_dL_g",
        "selection_basis": "high-coverage solution property",
    },
    {
        "category": "stability",
        "property": "water_absorption_pct",
        "selection_basis": "high-coverage stability property",
    },
    {
        "category": "surface",
        "property": "contact_angle_degree",
        "selection_basis": "representative surface property",
    },
    {
        "category": "transport",
        "property": "O2_perm_Barrer",
        "selection_basis": "representative gas-transport property",
    },
]


def score_summary(path: Path) -> dict[str, float | int]:
    columns = pd.read_csv(path, nrows=0).columns
    score_column = (
        "property_reliability_score"
        if "property_reliability_score" in columns
        else "reliability_score"
    )
    scores = pd.read_csv(path, usecols=[score_column])[score_column]
    scores = pd.to_numeric(scores, errors="coerce").dropna()
    return {
        "scored_n": int(len(scores)),
        "score_mean": float(scores.mean()),
        "score_median": float(scores.median()),
        "score_p10": float(scores.quantile(0.10)),
        "score_p90": float(scores.quantile(0.90)),
        "score_min": float(scores.min()),
        "score_max": float(scores.max()),
    }


def write_manifest(path: Path, rows: list[dict[str, object]]) -> None:
    pd.DataFrame(rows).to_csv(path.with_suffix(".csv"), index=False, encoding="utf-8-sig")
    path.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dataset",
        type=Path,
        default=root / "input_data" / "merged dataset" / "dataset_v10_maccs_drop30_invalidpsmiles.csv",
    )
    parser.add_argument(
        "--missing-dir",
        type=Path,
        default=root / "outputs" / "03_missing_predictions",
    )
    parser.add_argument(
        "--coordinates-csv",
        type=Path,
        default=root
        / "outputs"
        / "14_structural_embedding_comparison"
        / "coordinates_maccs_k_200_min_dist_0_35_pca_init.csv",
    )
    parser.add_argument(
        "--existing-class-csv",
        type=Path,
        default=Path(
            "D:/nexpoly/visualization/results/12_v10_motif_category_heatmap/"
            "polymer_classes_v10.csv"
        ),
    )
    parser.add_argument(
        "--base-output-dir",
        type=Path,
        default=root
        / "outputs"
        / "22_representative_property_reliability_umaps_05_10_no_legend_overlap",
    )
    parser.add_argument(
        "--reliability-assignment-root",
        type=Path,
        default=None,
        help=(
            "Optional root containing one historical assignment snapshot per "
            "category/property directory."
        ),
    )
    parser.add_argument("--display-quantile", type=float, default=0.05)
    parser.add_argument("--point-size", type=float, default=42.0)
    parser.add_argument("--figure-width", type=float, default=11.4)
    parser.add_argument("--figure-height", type=float, default=6.15)
    args = parser.parse_args()

    args.dataset = args.dataset.resolve()
    args.missing_dir = args.missing_dir.resolve()
    args.coordinates_csv = args.coordinates_csv.resolve()
    args.existing_class_csv = args.existing_class_csv.resolve()
    args.base_output_dir = args.base_output_dir.resolve()
    if args.reliability_assignment_root is not None:
        args.reliability_assignment_root = args.reliability_assignment_root.resolve()
    args.base_output_dir.mkdir(parents=True, exist_ok=True)

    dataset = pd.read_csv(args.dataset)
    if "smiles" not in dataset.columns:
        raise ValueError(f"Dataset lacks smiles column: {args.dataset}")
    plot_script = Path(__file__).resolve().parent / "15_plot_polymer_class_knowledge_gap_umap.py"
    manifest_path = args.base_output_dir / "representative_property_manifest.json"
    rows: list[dict[str, object]] = []

    for item in REPRESENTATIVE_PROPERTIES:
        category = item["category"]
        property_name = item["property"]
        if property_name not in dataset.columns:
            raise ValueError(f"Property {property_name} is absent from {args.dataset}")
        assignment_path = None
        if args.reliability_assignment_root is not None:
            assignment_path = (
                args.reliability_assignment_root
                / f"{category}_{property_name}"
                / f"polymer_class_and_{property_name}_reliability_assignments.csv.gz"
            )
            if not assignment_path.exists():
                raise FileNotFoundError(
                    f"Historical assignment snapshot not found: {assignment_path}"
                )

        score_path = assignment_path or (
            args.missing_dir / f"{property_name}_missing_reliability.csv"
        )
        if not score_path.exists():
            raise FileNotFoundError(f"Missing reliability file: {score_path}")

        output_dir = args.base_output_dir / f"{category}_{property_name}"
        observed_n = int(pd.to_numeric(dataset[property_name], errors="coerce").notna().sum())
        missing_n = int(len(dataset) - observed_n)
        summary = score_summary(score_path)
        row: dict[str, object] = {
            "category": category,
            "property": property_name,
            "selection_basis": item["selection_basis"],
            "observed_n": observed_n,
            "missing_n": missing_n,
            **summary,
            "output_dir": str(output_dir),
            "status": "running",
        }
        rows.append(row)
        write_manifest(manifest_path, rows)

        command = [
            sys.executable,
            str(plot_script),
            "--property",
            property_name,
            "--dataset",
            str(args.dataset),
            "--missing-dir",
            str(args.missing_dir),
            "--existing-class-csv",
            str(args.existing_class_csv),
            "--coordinates-csv",
            str(args.coordinates_csv),
            "--output-dir",
            str(output_dir),
            "--display-quantile",
            str(args.display_quantile),
            "--point-size",
            str(args.point_size),
            "--figure-width",
            str(args.figure_width),
            "--figure-height",
            str(args.figure_height),
        ]
        if assignment_path is not None:
            command.extend(
                [
                    "--reliability-assignment-file",
                    str(assignment_path),
                ]
            )
        print("RUN:", " ".join(command), flush=True)
        completed = subprocess.run(command, check=False)
        if completed.returncode != 0:
            row["status"] = f"error_exit_{completed.returncode}"
            write_manifest(manifest_path, rows)
            return completed.returncode

        row["status"] = "success"
        row["png"] = str(output_dir / f"polymer_class_and_{property_name}_reliability_umap.png")
        row["pdf"] = str(output_dir / f"polymer_class_and_{property_name}_reliability_umap.pdf")
        write_manifest(manifest_path, rows)

    summary = {
        "n_figures": len(rows),
        "color_scale": {
            "cmap": "RdYlGn",
            "vmin": 0.5,
            "vmax": 1.0,
            "values_below_0.5_clipped": True,
        },
        "display_quantile_per_axis": args.display_quantile,
        "point_size": args.point_size,
        "figure_width_inches": args.figure_width,
        "figure_height_inches": args.figure_height,
        "coordinate_source": str(args.coordinates_csv),
        "manifest_csv": str(manifest_path.with_suffix(".csv")),
        "manifest_json": str(manifest_path),
    }
    (args.base_output_dir / "method.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
